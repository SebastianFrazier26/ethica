"""Re-run blind framework identification with other judge descriptions (D-74).

    uv run python scripts/v1_rejudge_identification.py configs/experiments/v1-pilot-s0.yaml \
        --descriptions configs/judge/identify-v2.yaml --tag id2

Writes `<config stem>-<tag>.yaml` beside the config: same experiment name (episode ids are scoped
by it), `out_dir: runs/<name>-<tag>`, and `judge.identify_descriptions` set. The first run copies
the original database there and deletes only its identification scores; the judge phase then
re-judges identification and nothing else. The original run is never touched, so both versions
stay readable side by side (`scripts/v1_gate.py` on either config). Rerunning resumes.
"""

from __future__ import annotations

import argparse
import shutil
import sqlite3
from pathlib import Path

import yaml

from ethica.config import load_config
from ethica.orchestrator import judge
from ethica.scoring.judge import IDENTIFY_PREFIX

ROOT = Path(__file__).resolve().parent.parent


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("config", type=Path)
    ap.add_argument("--descriptions", type=Path, required=True)
    ap.add_argument("--tag", default="id2")
    args = ap.parse_args()
    src_cfg = load_config(args.config)
    raw = yaml.safe_load(args.config.read_text(encoding="utf-8"))
    out_dir = f"runs/{src_cfg.name}-{args.tag}"
    raw["out_dir"] = out_dir
    raw.setdefault("judge", {})["identify_descriptions"] = str(args.descriptions)
    new_path = args.config.with_name(f"{args.config.stem}-{args.tag}.yaml")
    header = (
        f"# Generated by scripts/v1_rejudge_identification.py from {args.config.name}: "
        f"identification re-judged with {args.descriptions} (D-74).\n"
    )
    new_path.write_text(header + yaml.safe_dump(raw, sort_keys=False), encoding="utf-8")
    cfg = load_config(new_path)
    db = Path(cfg.resolved_db_url.removeprefix("sqlite:///"))
    if not db.exists():
        src_db = Path(src_cfg.resolved_db_url.removeprefix("sqlite:///"))
        if not src_db.exists():
            raise SystemExit(f"{src_db} missing: score {args.config} first")
        db.parent.mkdir(parents=True, exist_ok=True)
        tmp = db.with_suffix(".partial")
        shutil.copy(src_db, tmp)
        con = sqlite3.connect(tmp)
        n = con.execute(
            "delete from scores where metric like ? || '%'", (IDENTIFY_PREFIX,)
        ).rowcount
        con.commit()
        con.close()
        tmp.rename(db)
        print(f"copied {src_db} -> {db}; removed {n} identification scores")
    judge(cfg)


if __name__ == "__main__":
    main()
